CREATE OR REPLACE FUNCTION aa.mirea_blocked(TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog AS $$
 SELECT EXISTS(SELECT 1 FROM aa.mirea_bans WHERE pulse_uid=$1 AND blocked)
 OR EXISTS(SELECT 1 FROM aaid.users u JOIN aaid.mirea_links m ON m.user_id=u.id WHERE m.pulse_uid=$1 AND u.status='blocked')
$$;
REVOKE ALL ON FUNCTION aa.mirea_blocked(TEXT) FROM PUBLIC;
CREATE OR REPLACE FUNCTION aa.record_login(TEXT,TEXT) RETURNS VOID
LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog AS $$
 INSERT INTO aa.usage_events(created,kind,actor_mirea,target_mirea,details)
 SELECT EXTRACT(EPOCH FROM CURRENT_TIMESTAMP),'login',pulse_uid,pulse_uid,jsonb_build_object('channel',$2)
 FROM aaid.mirea_links WHERE user_id=$1
$$;
REVOKE ALL ON FUNCTION aa.record_login(TEXT,TEXT) FROM PUBLIC;
CREATE OR REPLACE FUNCTION aa.set_mirea_ban(TEXT,BOOLEAN,TEXT) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended($1,6067703));
 PERFORM pg_advisory_xact_lock(6067702);
 INSERT INTO aa.mirea_bans VALUES($1,$2,$3,EXTRACT(EPOCH FROM CURRENT_TIMESTAMP))
 ON CONFLICT(pulse_uid) DO UPDATE SET blocked=EXCLUDED.blocked,reason=EXCLUDED.reason,updated_at=EXCLUDED.updated_at;
 UPDATE aaid.users SET status=CASE WHEN $2 THEN 'blocked' ELSE 'active' END WHERE id IN(SELECT user_id FROM aaid.mirea_links WHERE pulse_uid=$1);
 IF $2 THEN
  UPDATE aaid.sessions SET revoked_at=EXTRACT(EPOCH FROM CURRENT_TIMESTAMP),revoke_reason='mirea_ban'
   WHERE user_id IN(SELECT user_id FROM aaid.mirea_links WHERE pulse_uid=$1) AND revoked_at IS NULL;
  DELETE FROM aa.site_sessions WHERE mirea=$1;
 END IF;
 UPDATE aa.accounts SET state=CASE WHEN $2 THEN 'blocked' ELSE 'expired' END,session_version=session_version+1,version=version+1 WHERE pulse_id=$1;
 INSERT INTO aa.usage_events(created,kind,actor_mirea,target_mirea,details) VALUES(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP),'moderation',NULL,$1,jsonb_build_object('blocked',$2,'reason',$3));
 PERFORM pg_notify('aa_events','');
END $$;
REVOKE ALL ON FUNCTION aa.set_mirea_ban(TEXT,BOOLEAN,TEXT) FROM PUBLIC;
CREATE OR REPLACE FUNCTION aa.identity_active(TEXT,TEXT,TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog AS $$
 SELECT EXISTS(SELECT 1 FROM aaid.users u JOIN aaid.mirea_links m ON m.user_id=u.id
 JOIN aaid.sessions s ON s.user_id=u.id WHERE u.id=$1 AND m.pulse_uid=$2
 AND s.id=$3 AND u.status='active' AND s.revoked_at IS NULL
 AND s.expires>EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) AND NOT aa.mirea_blocked($2))
$$;
REVOKE ALL ON FUNCTION aa.identity_active(TEXT,TEXT,TEXT) FROM PUBLIC;
CREATE OR REPLACE FUNCTION aa.identity_context(TEXT,TEXT,TEXT) RETURNS TABLE(group_id BIGINT,group_name TEXT)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog AS $$
 SELECT m.group_id,m.group_name FROM aaid.users u JOIN aaid.mirea_links m ON m.user_id=u.id
 JOIN aaid.sessions s ON s.user_id=u.id WHERE u.id=$1 AND m.pulse_uid=$2
 AND s.id=$3 AND u.status='active' AND s.revoked_at IS NULL
 AND s.expires>EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) AND NOT aa.mirea_blocked($2)
$$;
REVOKE ALL ON FUNCTION aa.identity_context(TEXT,TEXT,TEXT) FROM PUBLIC;
